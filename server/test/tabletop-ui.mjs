import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { mkdirSync } from 'node:fs';
import { once } from 'node:events';
import { chromium } from 'playwright-core';
import { startServer } from '../src/main.ts';
import { DEFAULT_TIMING } from '../src/room.ts';
import { createGame } from '../../engine/src/engine.ts';
import { CARDS } from '../../engine/src/cards.ts';
const srv = startServer(0, { ...DEFAULT_TIMING, fakeDelayMin: 0, fakeDelayMax: 0 });
await once(srv.wss, 'listening');
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || undefined });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 960 } });
  const a = await context.newPage(), b = await context.newPage();
  const errors = [];
  for (const p of [a,b]) { p.on('pageerror', e => errors.push(e.message)); await p.goto(`http://127.0.0.1:${srv.wss.address().port}/`); await p.waitForFunction(() => window.__xhs?.ws?.readyState === 1); }
  await a.click('#btn-create');
  await a.waitForFunction(() => document.querySelector('#room-code').textContent.length === 6);
  const code = await a.textContent('#room-code');
  await b.fill('#in-code', code); await b.click('#btn-join');
  await a.click('[data-f="sweet"]'); await b.click('[data-f="savory"]');
  await a.waitForFunction(() => window.__xhs.view);
  const s = createGame(CARDS, ['sweet','savory'], 1);
  s.phase = {kind:'play',active:0}; s.round = 3;
  s.players[0].hand = [1,25,6,19,53,64,2,7].map((id,i) => ({uid:900+i,defId:`XHS-${String(id).padStart(3,'0')}`}));
  s.players[0].hp = 6;
  srv.rooms.get(code).commitState(s,null);
  await a.waitForFunction(() => window.__xhs.view.players[0].hand.length === 8);
  await a.mouse.move(0,0);
  assert.equal(await a.isVisible('#preview-image'), false);
  await a.locator('#my-hand [data-def="XHS-025"]').hover();
  assert.match(await a.locator('#preview-image').getAttribute('src'), /XHS-025.jpg$/);
  assert.match(await a.textContent('#card-detail'), /林广/);
  assert.equal(await a.locator('#my-hand img').evaluateAll(imgs => imgs.every(i => i.complete && i.naturalWidth > 0 && getComputedStyle(i.parentElement).filter === 'none')), true);
  mkdirSync(new URL('../../art/previews/',import.meta.url),{recursive:true});
  await a.mouse.move(0,0);
  assert.equal(await a.isVisible('#preview-image'), false);
  assert.match(await a.textContent('#card-detail'), /悬停或聚焦/);
  assert.equal(await a.locator('.stat-icon').evaluateAll(imgs => imgs.every(i => i.complete && i.naturalWidth > 0)), true);
  await a.screenshot({path:fileURLToPath(new URL('../../art/previews/tabletop-desktop.png',import.meta.url)),fullPage:true});
  for (const [width,height] of [[1920,1080],[1440,900],[1280,800],[1024,768],[768,1024],[390,844]]) {
    await a.setViewportSize({width,height});
    assert.equal(await a.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true,`page overflow at ${width}`);
    await a.locator('#my-hand .card').last().scrollIntoViewIfNeeded();
    assert.equal(await a.locator('#my-hand .card').last().isVisible(),true);
    const card = a.locator('#my-hand .card').first();
    await card.scrollIntoViewIfNeeded(); await card.hover(); await a.waitForTimeout(180);
    assert.equal(await card.evaluate(el => {
      const hand = document.querySelector('#my-hand').getBoundingClientRect();
      const field = document.querySelector('#my-field').getBoundingClientRect();
      const top = (el.querySelector('.x') ?? el).getBoundingClientRect().top;
      return top >= hand.top && top >= field.bottom;
    }), true, `hovered card/badge clipped at ${width}`);
  }
  await a.getByRole('button',{name:'规则',exact:true}).click();
  assert.equal(await a.isVisible('#modal'),true);
  await a.click('#rules-close');
  await a.setViewportSize({width:1280,height:800});
  await a.locator('#my-hand [data-def="XHS-025"]').focus();
  await a.keyboard.press('Enter');
  await a.waitForFunction(() => window.__xhs.view.players[0].hand.length === 7);
  await b.waitForFunction(() => [...document.querySelectorAll('.log-card')].some(el => el.dataset.def === 'XHS-025'));
  const historyCard = b.locator('.log-card[data-def="XHS-025"]').last();
  await historyCard.hover();
  assert.match(await b.locator('#preview-image').getAttribute('src'), /XHS-025.jpg$/);
  await b.mouse.move(0,0); assert.equal(await b.isVisible('#preview-image'), false);
  await historyCard.click();
  assert.equal(await b.isVisible('#card-reader'), true);
  assert.match(await b.locator('#reader-image').getAttribute('src'), /XHS-025.jpg$/);
  assert.ok((await b.textContent('#reader-text')).length > 0);
  await b.keyboard.press('Escape'); assert.equal(await b.isVisible('#card-reader'), false);
  // Real attack and defense window: attacker gets only a waiting event, defender gets the response phase.
  const battle = createGame(CARDS, ['sweet','savory'], 1);
  battle.phase = {kind:'play',active:0};
  battle.players[0].hand = [{uid:990,defId:'XHS-023'}];
  battle.players[1].hand = [{uid:991,defId:'XHS-001'}];
  srv.rooms.get(code).commitState(battle,null);
  await a.waitForFunction(() => window.__xhs.view.players[0].hand[0]?.uid === 990);
  await a.locator('#my-hand .card').click();
  await b.waitForFunction(() => window.__xhs.view.phase.kind === 'response');
  await a.waitForFunction(() => document.querySelector('#status').textContent.includes('等待对手防御中'));
  assert.match(await a.textContent('#status'), /等待对手防御中/);
  assert.match(await b.textContent('#status'), /请选择防御或反制牌/);
  await a.waitForTimeout(300);
  assert.match(await a.textContent('#clock'), /响应结束后/);
  await b.getByRole('button',{name:'放弃',exact:true}).click();
  await a.waitForFunction(() => !document.querySelector('#status').textContent.includes('等待对手防御中'));
  assert.deepEqual(errors,[]);
  console.log('PASS: original icons, transient previews, unclipped hand at six viewports, opponent history reader, defense prompts, keyboard play');
} finally { await browser.close(); await srv.close(); }
